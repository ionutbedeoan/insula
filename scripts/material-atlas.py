"""Pack local CC0 source maps. Run with Pillow: python scripts/material-atlas.py SOURCE_DIR OUTPUT_TS."""
import base64
import io
from pathlib import Path
import sys
from PIL import Image

source = Path(sys.argv[1])
tile, pad = 512, 12
names = ["forest_floor", "mossy_rock", "rock_boulder_dry", "weathered_planks", "palm_bark"]
sand = next((name for name in ["sand", "sand_01", "coast_sand", "gravelly_sand", "beach_sand_01"]
             if all((source / f"{name}-{role}.jpg").exists() for role in ["diff", "nor_gl"])), None)
names += [sand or "forest_floor"]

output = ["// Generated by scripts/material-atlas.py. Poly Haven, CC0."]
for kind, identifier in [("diff", "albedoAsset"), ("nor_gl", "normalAsset")]:
    atlas = Image.new("RGB", (tile*4, tile*2), (128,128,255) if kind == "nor_gl" else (123,112,96))
    for idx, name in enumerate(names):
        im = Image.open(source / f"{name}-{kind}.jpg").convert("RGB").resize((tile-2*pad,tile-2*pad),Image.Resampling.LANCZOS)
        ox, oy = idx%4*tile, idx//4*tile
        w, h = im.size
        atlas.paste(im,(ox+pad,oy+pad))
        strips = [(im.crop((w-pad,0,w,h)),ox,oy+pad),(im.crop((0,0,pad,h)),ox+tile-pad,oy+pad),
                  (im.crop((0,h-pad,w,h)),ox+pad,oy),(im.crop((0,0,w,pad)),ox+pad,oy+tile-pad)]
        for img,x,y in strips: atlas.paste(img,(x,y))
        for x in [0,1]:
            for y in [0,1]:
                sx,sy=(w-pad)*(1-x),(h-pad)*(1-y)
                atlas.paste(im.crop((sx,sy,sx+pad,sy+pad)),(ox+x*(tile-pad),oy+y*(tile-pad)))
    data=io.BytesIO()
    atlas.save(data, "WEBP", quality=82 if kind=="diff" else 81, method=6)
    output.append(f"export const {identifier}='data:image/webp;base64,{base64.b64encode(data.getvalue()).decode()}'")
Path(sys.argv[2]).write_text("\n".join(output)+"\n")
print(", ".join(names))
