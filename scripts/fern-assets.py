"""Pack the CC0 Poly Haven Fern 02 scan into the portable browser build."""
import base64
import io
import json
from pathlib import Path
import sys
from PIL import Image
import struct

folder=Path(sys.argv[1])
gltf=json.loads((folder/"fern_02.gltf").read_text())
binary=(folder/"fern_02.bin").read_bytes()
def data(index):
    accessor=gltf["accessors"][index]
    view=gltf["bufferViews"][accessor["bufferView"]]
    start=view.get("byteOffset",0)+accessor.get("byteOffset",0)
    length={"SCALAR":1,"VEC2":2,"VEC3":3}[accessor["type"]]
    fmt="<"+("f" if accessor["componentType"]==5126 else "H")*length
    step=view.get("byteStride",struct.calcsize(fmt))
    return [struct.unpack_from(fmt,binary,start+i*step) for i in range(accessor["count"])]
def b64(raw):
    return base64.b64encode(raw).decode()

shape=[]
for mesh in (2,3,0):
    m=gltf["meshes"][mesh]["primitives"][0]
    position=data(m["attributes"]["POSITION"])
    left,right=min(p[0] for p in position),max(p[0] for p in position)
    bottom=min(p[1] for p in position)
    back,front=min(p[2] for p in position),max(p[2] for p in position)
    vertices=[v for x,y,z in position for v in (x-(left+right)*.5,y-bottom,z-(back+front)*.5)]
    normals=[v for p in data(m["attributes"]["NORMAL"]) for v in p]
    uv=[v for p in data(m["attributes"]["TEXCOORD_0"]) for v in p]
    index=[i for i, in data(m["indices"])]
    shape.append(dict(p=b64(struct.pack(f"<{len(vertices)}f",*vertices)),
                      n=b64(struct.pack(f"<{len(normals)}f",*normals)),
                      u=b64(struct.pack(f"<{len(uv)}f",*uv)),
                      i=b64(struct.pack(f"<{len(index)}H",*index))))
color=Image.open(folder/"fern_02_diff_1k.jpg").convert("RGB").resize((768,768),Image.Resampling.LANCZOS)
mask=Image.open(folder/"fern_02_alpha.png").convert("L").resize((768,768),Image.Resampling.LANCZOS)
color.putalpha(mask)
buffer=io.BytesIO()
color.save(buffer,"WEBP",quality=86,method=6)
Path(sys.argv[2]).write_text("// Poly Haven Fern 02 scanned fronds, CC0. Generated by scripts/fern-assets.py.\n"+
    f"export const fernPixels='data:image/webp;base64,{b64(buffer.getvalue())}'\n"+
    "export const fernMeshes="+json.dumps(shape,separators=(",",":"))+"\n")
if len(sys.argv)>3: Path(sys.argv[3]).write_bytes(buffer.getvalue())
